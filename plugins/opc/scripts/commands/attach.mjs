import { spawnSync } from 'node:child_process';
import { accessSync, chmodSync, constants, writeFileSync } from 'node:fs';
import { delimiter, isAbsolute, join } from 'node:path';
import { parseArgs, shellQuote } from '../lib/args.mjs';
import { ExitCode, OpcError, UsageError } from '../lib/opc-error.mjs';
import { openApi } from '../lib/context.mjs';
import { assertId } from '../lib/api.mjs';
import { attachSecretPath, readServerRecord, resolveOpencodeBin, writeAttachSecret } from '../lib/server.mjs';
import { listJobs } from '../lib/jobs.mjs';
import { renderAttach } from '../lib/render.mjs';

export const PANE_SCRIPT_NAME = 'attach-pane.sh';
export const PANE_SCRIPT = `#!/bin/sh
# Generated by opc (attach --pane). Reads the OpenCode server password from a
# 0600 file inside the pane, so it never appears in any process argv.
set -eu
secret_file=$1
opencode_bin=$2
directory=$3
shift 3
OPENCODE_SERVER_PASSWORD=$(cat "$secret_file")
export OPENCODE_SERVER_PASSWORD
cd "$directory"
exec "$opencode_bin" "$@"
`;

const SPEC = { flags: { pane: { type: 'boolean' }, json: { type: 'boolean' }, cwd: { type: 'string' } }, allowPositionals: true };

export function resolveExecutable(name, pathEnv = process.env.PATH ?? '') {
  if (isAbsolute(name)) return name;
  for (const dir of String(pathEnv).split(delimiter).filter(Boolean)) {
    const candidate = join(dir, name);
    try { accessSync(candidate, constants.X_OK); return candidate; } catch { /* continue */ }
  }
  return name;
}

export function buildAttachArgs({ url, sessionID, directory }) {
  return ['--server', url, ...(sessionID ? ['-s', sessionID] : [])];
}

export async function persistManagedAttachSecret(ctx, server) {
  const { withServerLock } = await import('../lib/jobs.mjs');
  return withServerLock(ctx, () => {
    const current = readServerRecord(ctx.stateDir);
    // ensureServer returns url/pid/port/password (no startTime); the per-server random password pins the identity
    const sameIdentity = current
      && current.url === server.url
      && current.pid === server.pid
      && current.port === server.port
      && current.password === server.password;
    if (!sameIdentity) {
      throw new UsageError('SERVER_CHANGED', 'O registro do servidor gerenciado não existe ou mudou durante o attach; tente novamente.');
    }
    writeAttachSecret(ctx.stateDir, current.password);
  }, { purpose: 'attach-secret' });
}

function lastJobSession(ctx) {
  const jobs = listJobs(ctx.stateDir, { claudeSessionId: ctx.claudeSessionId, all: !ctx.claudeSessionId })
    .filter((job) => job.sessionID && !job.groupId)
    .sort((a, b) => String(b.updatedAt ?? b.createdAt ?? '').localeCompare(String(a.updatedAt ?? a.createdAt ?? '')));
  return jobs[0]?.sessionID ?? null;
}

function envWithoutSecrets(env) {
  const copy = { ...env };
  delete copy.OPENCODE_SERVER_PASSWORD;
  delete copy.OPC_SERVER_PASSWORD;
  return copy;
}

export async function run(ctx, argv) {
  const { flags, positionals } = parseArgs(argv, SPEC);
  if (positionals.length > 1) throw new UsageError('USAGE', `Argumento inesperado: ${preview(positionals[1])}`);
  const explicit = positionals[0] ? assertId('ses', positionals[0], 'sessão') : null;
  if (flags.pane && !ctx.env.TMUX) {
    throw new UsageError('NOT_IN_TMUX', '--pane só funciona dentro do tmux ($TMUX vazio). Rode /opc:attach sem --pane e use a linha exibida num terminal.');
  }
  const conn = await openApi(ctx);
  try {
    const { server, api } = conn;
    const sessionID = explicit ?? lastJobSession(ctx);
    if (sessionID) await api.getSession(sessionID);
    const attached = Boolean(server.attached);
    if (flags.pane && attached) {
      throw new UsageError('PANE_ATTACHED_MODE', '--pane não funciona com OPC_SERVER_URL porque o opc não guarda a senha do servidor externo. Use a linha exibida sem --pane.');
    }
    const directory = ctx.workspaceRoot;
    const authSource = attached
      ? { type: 'env', name: 'OPC_SERVER_PASSWORD' }
      : { type: 'file', path: attachSecretPath(ctx.stateDir) };
    const attachArgs = buildAttachArgs({ url: server.url, sessionID, directory });
    const opencodeBin = resolveOpencodeBin({ env: ctx.env, config: ctx.config });
    const info = { url: server.url, sessionID, directory, attached, authSource, argv: [opencodeBin, ...attachArgs] };
    if (!attached) await persistManagedAttachSecret(ctx, server);

    if (flags.pane) {
      const scriptPath = join(ctx.stateDir, PANE_SCRIPT_NAME);
      writeFileSync(scriptPath, PANE_SCRIPT, { mode: 0o700 });
      chmodSync(scriptPath, 0o700);
      const executable = resolveExecutable(opencodeBin, ctx.env.PATH);
      const paneCommand = ['/bin/sh', scriptPath, authSource.path, executable, directory, ...info.argv.slice(1)].map(shellQuote).join(' ');
      const res = spawnSync('tmux', ['split-window', '-h', '-P', '-F', '#{pane_id}', '-c', directory, paneCommand], {
        env: envWithoutSecrets(ctx.env), encoding: 'utf8', shell: false,
      });
      if (res.error || res.status !== 0) {
        throw new OpcError('TMUX_FAILED', 'tmux split-window falhou ao abrir o pane.', { exitCode: ExitCode.USAGE });
      }
      info.pane = { id: String(res.stdout).trim() };
    }

    if (flags.json) ctx.json(info);
    else ctx.out(renderAttach(info));
    return ExitCode.OK;
  } finally {
    conn.close();
  }
}

function preview(value) { return `${String(value).slice(0, 12)}…`; }
